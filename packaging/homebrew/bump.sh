#!/bin/sh
# Render Casks/runtime-desk.rb for the newest published Runtime Desk release.
#
# The cask is generated, never hand-edited: a cask's sha256 only exists once the
# release asset does, and releases here are immutable (an asset can never be
# added to one afterwards), so the checksum lives in the release's SHA256SUMS.txt
# and this script copies it into the cask.
#
#   bump.sh                     # newest release via gh, write Casks/runtime-desk.rb
#   bump.sh --dry-run           # same, but print the cask instead of writing it
#   bump.sh --version 1.1.3 --sums FILE
#                               # offline: render from a local SHA256SUMS.txt
#
# Runs from a tap checkout (the directory holding Casks/) and as the body of
# .github/workflows/bump.yml.
set -eu

repo=dm0xa/runtime-desk
out=Casks/runtime-desk.rb
dry_run=false
version=
sums_file=

while [ $# -gt 0 ]; do
	case $1 in
	--dry-run) dry_run=true ;;
	--version) version=${2:?--version needs a value}; shift ;;
	--sums) sums_file=${2:?--sums needs a path}; shift ;;
	*) echo "bump.sh: unknown argument $1" >&2; exit 2 ;;
	esac
	shift
done

if [ -z "$version" ]; then
	tag=$(gh api "repos/$repo/releases/latest" --jq .tag_name)
	version=${tag#v}
fi
[ -n "$version" ] || { echo "bump.sh: no release to read" >&2; exit 1; }

if [ -z "$sums_file" ]; then
	sums=$(gh release download "v$version" -R "$repo" -p SHA256SUMS.txt -O -)
else
	sums=$(cat "$sums_file")
fi

# One line per architecture, as `<sha>  <asset>`; the asset name carries the
# version and the release's own spelling (spaces already rewritten to dots).
arm_line=$(printf '%s\n' "$sums" | awk '$2 ~ /_aarch64\.dmg$/')
intel_line=$(printf '%s\n' "$sums" | awk '$2 ~ /_x86_64\.dmg$/')
[ -n "$arm_line" ] || { echo "bump.sh: SHA256SUMS.txt has no aarch64 disk image for v$version" >&2; exit 1; }
[ -n "$intel_line" ] || { echo "bump.sh: SHA256SUMS.txt has no x86_64 disk image for v$version" >&2; exit 1; }

arm_sha=$(printf '%s' "$arm_line" | awk '{print $1}')
arm_asset=$(printf '%s' "$arm_line" | awk '{print $2}')
intel_sha=$(printf '%s' "$intel_line" | awk '{print $1}')
intel_asset=$(printf '%s' "$intel_line" | awk '{print $2}')

# The disk-image names carry the version, so the url must interpolate it in the
# file name as well: a url with a literal version reads as unversioned to the
# audit, which then demands sha256 :no_check instead of the pinned checksum.
arm_url=$(printf '%s' "$arm_asset" | sed "s/_${version}_/_#{version}_/")
intel_url=$(printf '%s' "$intel_asset" | sed "s/_${version}_/_#{version}_/")

render() {
	cat <<EOF
# Generated by bump.sh from https://github.com/$repo/releases/tag/v$version —
# edit packaging/homebrew/bump.sh in the app repo, not this file.
cask "runtime-desk" do
  version "$version"

  on_arm do
    sha256 "$arm_sha"

    url "https://github.com/$repo/releases/download/v#{version}/$arm_url"
  end
  on_intel do
    sha256 "$intel_sha"

    url "https://github.com/$repo/releases/download/v#{version}/$intel_url"
  end

  name "Runtime Desk"
  desc "One window over Colima, Docker and Podman"
  homepage "https://github.com/$repo"

  depends_on macos: :ventura

  app "Runtime Desk.app"

  # The app is ad-hoc signed (no Developer ID, no notarization), so a quarantined
  # copy is refused by Gatekeeper with "damaged and can't be opened". The flag is
  # stripped only when the signature really is ad-hoc, so a future notarized build
  # keeps the protection it earned.
  postflight_steps do
    run "/bin/sh",
        args:           ["-c",
                         "/usr/bin/codesign -dv \"\$1\" 2>&1 | /usr/bin/grep -q Signature=adhoc && " \\
                         "/usr/bin/xattr -dr com.apple.quarantine \"\$1\"",
                         "sh", "{{appdir}}/Runtime Desk.app"],
        writable_paths: ["{{appdir}}/Runtime Desk.app"],
        must_succeed:   false,
        print_stderr:   false
  end

  uninstall quit: "io.github.dm0xa.runtimedesk"

  zap trash: [
    "~/Library/Application Support/io.github.dm0xa.runtimedesk",
    "~/Library/Caches/io.github.dm0xa.runtimedesk",
    "~/Library/HTTPStorages/io.github.dm0xa.runtimedesk",
    "~/Library/Preferences/io.github.dm0xa.runtimedesk.plist",
    "~/Library/Saved Application State/io.github.dm0xa.runtimedesk.savedState",
    "~/Library/WebKit/io.github.dm0xa.runtimedesk",
  ]
end
EOF
}

if $dry_run; then
	render
	exit 0
fi

mkdir -p "$(dirname "$out")"
tmp=$(mktemp)
render >"$tmp"
if [ -f "$out" ] && cmp -s "$tmp" "$out"; then
	rm -f "$tmp"
	echo "cask already names v$version"
	exit 0
fi
mv "$tmp" "$out"
echo "cask now names v$version"
